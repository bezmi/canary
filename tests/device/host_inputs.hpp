// One declared state of a fixture: raw mass fractions, density [kg/m^3],
// translational temperature [K] and mode temperatures [K] in model mode order.
template <std::size_t N, std::size_t M> struct FixtureState {
    std::array<double, N> y;
    double rho;
    double temp;
    std::array<double, M> modes;
};

// The inputs derived from one fixture state by a forward closure of its model
// in binary64 and SI units (derived_inputs.hpp, generated by
// derive_inputs.cpp): density, specific energy, pressure and mode specific
// energies. Products of these with the density or the mass fractions (energy
// densities, partial densities) are formed on the host in binary64.
template <std::size_t M> struct DerivedState {
    double rho;
    double e;
    double p;
    std::array<double, M> mode_e;
};

// The rates of progress of a mechanism of R reactions at one fixture state, in
// particles/(m^3 s): derived by evaluation of the mechanism in binary64 and SI
// units (derived_inputs.hpp), or declared independently.
template <std::size_t R> struct DerivedRates {
    std::array<double, R> forward;
    std::array<double, R> backward;
};

