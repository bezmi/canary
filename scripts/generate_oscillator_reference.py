#!/usr/bin/env python3
"""Generate binary64 oscillator references using Python's decimal module.

Run from the repository root:
    python3 scripts/generate_oscillator_reference.py --output tests/oscillator_reference.hpp

The output is checked at 800 and 1000 decimal digits before rounding to binary64.
No Canary evaluator is used. See scripts/oscillator-reference.md for the formula,
input provenance, precision requirements and representation.
"""

import argparse
from decimal import Decimal, localcontext
from pathlib import Path


# SI dissociation energies [J/mol] and vibrational temperatures [K] from
# include/canary/data/air5_park_exchange.hpp, in chemistry_vibration order.
OSCILLATORS = (
    (945360.0, 3393.4559799744534),
    (498350.006, 2273.5451503935737),
    (630583.693, 2739.48872584259),
)
GAS_CONSTANT = 6.02214076e23 * 1.380649e-23


def arguments(theta_d):
    """Retain both signs, the zero limit and both sides of |theta_d*x| = 0.5."""
    yield 0.0
    for sign in (1.0, -1.0):
        yield sign * 1.0e-300
        for exponent in range(-12, -1):
            yield sign * float(f"1e{exponent}")
    for sign in (1.0, -1.0):
        for w in (0.1, 0.4999, 0.5, 0.5001, 1.0, 3.0, 10.0, 100.0, 1000.0, 1.0e4):
            yield sign * w / theta_d


def reference(theta_v, theta_d, x, precision):
    with localcontext() as context:
        context.prec = precision
        v, d, inverse_temperature = map(Decimal.from_float, (theta_v, theta_d, x))
        if not x:
            value = (d - v) / 2
        else:
            value = v / ((v * inverse_temperature).exp() - 1) - d / (
                (d * inverse_temperature).exp() - 1
            )
        return float(value)


def generate():
    lines = [
        "// Generated by scripts/generate_oscillator_reference.py; do not edit.",
        "// Direct oscillator formula at 800 and 1000 decimal digits, rounded to binary64.",
        "// Hexadecimal literals preserve the exact inputs and rounded reference values.",
        "#ifndef CANARY_TEST_OSCILLATOR_REFERENCE_HPP",
        "#define CANARY_TEST_OSCILLATOR_REFERENCE_HPP",
        "",
        "#include <array>",
        "",
        "namespace canary::test",
        "{",
        "struct OscillatorSample {",
        "    double inverse_temperature;  // 1/K",
        "    double energy_over_boltzmann;  // K",
        "};",
        "",
        "struct OscillatorReference {",
        "    double vibrational_temperature;  // K",
        "    double dissociation_temperature;  // K",
        "    std::array<OscillatorSample, 45> samples;",
        "};",
        "",
        "inline constexpr std::array<OscillatorReference, 3> oscillator_references {{",
    ]
    for energy, theta_v in OSCILLATORS:
        theta_d = energy / GAS_CONSTANT
        lines.append(f"    {{{theta_v.hex()}, {theta_d.hex()}, {{{{")
        count = 0
        for x in arguments(theta_d):
            value = reference(theta_v, theta_d, x, 800)
            check = reference(theta_v, theta_d, x, 1000)
            if value.hex() != check.hex():
                raise ArithmeticError(f"Precision disagreement for {(theta_v, theta_d, x)}")
            lines.append(f"        {{{x.hex()}, {value.hex()}}},")
            count += 1
        if count != 45:
            raise ValueError(f"Expected 45 arguments, got {count}")
        lines.append("    }}},")
    lines.extend([
        "}};",
        "}  // namespace canary::test",
        "",
        "#endif  // CANARY_TEST_OSCILLATOR_REFERENCE_HPP",
        "",
    ])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True, help="C++ reference header to replace")
    args = parser.parse_args()
    args.output.write_text(generate(), encoding="utf-8")


if __name__ == "__main__":
    main()
